def evaluate(model, loader, criterion):
    model.eval()
    total_loss = 0.0
    total_pixels = 0
    correct_pixels = 0
    confusion_matrix = np.zeros(
        (NUM_CLASSES, NUM_CLASSES), dtype=np.int64
    )

    with torch.no_grad():
        for im1, im2, target, _ in loader:
            im1 = im1.to(device)
            im2 = im2.to(device)
            target = target.to(device)

            outputs = model(im1, im2)
            loss = criterion(outputs, target)

            total_loss += loss.item()
            predictions = outputs.argmax(dim=1)

            valid = target != IGNORE_INDEX
            correct_pixels += (
                (predictions == target) & valid
            ).sum().item()
            total_pixels += valid.sum().item()

            add_to_confusion_matrix(
                confusion_matrix,
                target,
                predictions
            )

    accuracy = correct_pixels / max(total_pixels, 1)
    metrics = calculate_metrics(confusion_matrix)
    miou = metrics[1]

    return total_loss / len(loader), accuracy, miou

