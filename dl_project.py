import numpy as np

def compute_sek(confusion_matrix):
    """
    confusion_matrix: 7x7 numpy array (your test_cm)
    Returns: OA, mIoU, IoU_c, SeK
    Official SECOND implementation
    """
    cm = confusion_matrix.astype(np.float64)

    # 1. OA
    oa = np.diag(cm).sum() / cm.sum()

    # 2. mIoU over all 7 classes
    ious = []
    for i in range(7):
        tp = cm[i,i]
        fp = cm[:,i].sum() - tp
        fn = cm[i,:].sum() - tp
        denom = tp + fp + fn
        ious.append(tp/denom if denom!=0 else 0)
    miou = np.mean(ious)

    # 3. IoU_c (only changed classes 1-6)
    ious_c = ious[1:]
    iou_c = np.mean(ious_c)

    # 4. SeK - only on changed part
    q = cm[1:, 1:]  # remove no-change
    total_q = q.sum()
    if total_q == 0:
        return oa, miou, iou_c, 0.0

    # p0 - accuracy on changed
    p0 = np.diag(q).sum() / total_q

    # pe - chance agreement on changed
    row_sum = q.sum(axis=1)
    col_sum = q.sum(axis=0)
    pe = np.sum(row_sum * col_sum) / (total_q * total_q + 1e-10)

    kappa_c = (p0 - pe) / (1 - pe + 1e-10)

    # SeK = exp(IoU_c - 1) * Kappa_c
    sek = np.exp(iou_c - 1) * kappa_c

    return oa, miou, iou_c, sek, ious

