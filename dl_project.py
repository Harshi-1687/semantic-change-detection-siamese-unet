def calculate_metrics(cm):
    cm = cm.astype(np.float64)
    tp = np.diag(cm)
    actual = cm.sum(axis=1)
    predicted = cm.sum(axis=0)
    union = actual + predicted - tp

    iou = np.divide(
        tp, union,
        out=np.full(NUM_CLASSES, np.nan),
        where=union > 0
    )
    f1 = np.divide(
        2 * tp, actual + predicted,
        out=np.full(NUM_CLASSES, np.nan),
        where=(actual + predicted) > 0
    )

    accuracy = tp.sum() / max(cm.sum(), 1)
    miou = np.nanmean(iou)

    return accuracy, miou, iou, f1


def add_to_confusion_matrix(cm, target, prediction):
    target = target.detach().cpu().numpy().ravel()
    prediction = prediction.detach().cpu().numpy().ravel()

    valid = target != IGNORE_INDEX
    target = target[valid]
    prediction = prediction[valid]

    cm += confusion_matrix(
        target, prediction, labels=np.arange(NUM_CLASSES)
    )
    return cm


