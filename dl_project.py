    weighted_model.train()
    train_loss_sum = 0.0

    for t1, t2, target, _ in train_loader:
        t1 = t1.to(device, non_blocking=True)
        t2 = t2.to(device, non_blocking=True)
        target = target.to(device, non_blocking=True)

        weighted_optimizer.zero_grad(set_to_none=True)
        logits = weighted_model(t1, t2)
        loss = weighted_criterion(logits, target)

        if not torch.isfinite(loss):
            raise RuntimeError("Non-finite weighted training loss.")

        loss.backward()
        weighted_optimizer.step()
        train_loss_sum += loss.item()

    train_loss = train_loss_sum / len(train_loader)

    weighted_model.eval()
    val_loss_sum = 0.0
    val_cm = np.zeros((NUM_CLASSES, NUM_CLASSES), dtype=np.int64)

