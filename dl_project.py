class SECONDSemanticChangeDataset(Dataset):
    def __init__(self, root, split="train", size=256, augment=False):
        self.root = Path(root) / split
        self.files = sorted((self.root / "T1").glob("*.png"))
        self.size = size
        self.augment = augment

    def __len__(self):
        return len(self.files)

    def __getitem__(self, idx):
        name = self.files[idx].name

        with Image.open(self.root / "T1" / name) as im:
            im1 = im.convert("RGB").resize(
                (self.size, self.size), Image.Resampling.BILINEAR
            )

        with Image.open(self.root / "T2" / name) as im:
            im2 = im.convert("RGB").resize(
                (self.size, self.size), Image.Resampling.BILINEAR
            )

        with Image.open(self.root / "GT_T2" / name) as im:
            gt_t2 = np.array(im.resize(
                (self.size, self.size), Image.Resampling.NEAREST
            ), dtype=np.uint8).copy()

        with Image.open(self.root / "GT_CD" / name) as im:
            gt_cd = np.array(im.resize(
                (self.size, self.size), Image.Resampling.NEAREST
            ), dtype=np.uint8).copy()

        # Custom target:
        # 0 = no change; 1–6 = T2 class at changed pixels.
        # Ignore changed pixels whose T2 label is 0.
        target = np.zeros_like(gt_t2, dtype=np.uint8)
        changed = gt_cd == 255
        target[changed] = gt_t2[changed]
        target[changed & (gt_t2 == 0)] = IGNORE_INDEX

        im1 = TF.to_tensor(im1)
        im2 = TF.to_tensor(im2)
        target = torch.from_numpy(target.astype(np.int64))

        # Apply the same geometry to both images and target.
        if self.augment:
            if random.random() < 0.5:
                im1, im2 = TF.hflip(im1), TF.hflip(im2)
                target = TF.hflip(target.unsqueeze(0)).squeeze(0)

            if random.random() < 0.5:
                im1, im2 = TF.vflip(im1), TF.vflip(im2)
                target = TF.vflip(target.unsqueeze(0)).squeeze(0)

            k = random.randint(0, 3)
            if k:
                im1 = TF.rotate(im1, 90 * k)
                im2 = TF.rotate(im2, 90 * k)
                target = TF.rotate(
                    target.unsqueeze(0), 90 * k,
                    interpolation=TF.InterpolationMode.NEAREST
                ).squeeze(0)

        return im1, im2, target, name

