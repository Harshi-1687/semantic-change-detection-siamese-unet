import torch
import torch.nn as nn
import torch.nn.functional as F
device = "cuda"
class ConvBlock(nn.Module):
    def __init__(self, in_channels, out_channels):
        super().__init__()
        self.block = nn.Sequential(
            nn.Conv2d(in_channels, out_channels, 3, padding=1, bias=False),
            nn.BatchNorm2d(out_channels),
            nn.ReLU(inplace=True),
            nn.Conv2d(out_channels, out_channels, 3, padding=1, bias=False),
            nn.BatchNorm2d(out_channels),
            nn.ReLU(inplace=True)
        )

    def forward(self, x):
        return self.block(x)


class Encoder(nn.Module):
    def __init__(self):
        super().__init__()
        self.pool = nn.MaxPool2d(2)
        self.e1 = ConvBlock(3, 32)
        self.e2 = ConvBlock(32, 64)
        self.e3 = ConvBlock(64, 128)
        self.e4 = ConvBlock(128, 256)

    def forward(self, x):
        f1 = self.e1(x)                # 256 x 256
        f2 = self.e2(self.pool(f1))    # 128 x 128
        f3 = self.e3(self.pool(f2))    # 64 x 64
        f4 = self.e4(self.pool(f3))    # 32 x 32
        return f1, f2, f3, f4


class CBAM(nn.Module):
    def __init__(self, channels, reduction=8):
        super().__init__()
        hidden = max(channels // reduction, 8)

        self.channel_mlp = nn.Sequential(
            nn.Conv2d(channels, hidden, 1),
            nn.ReLU(inplace=True),
            nn.Conv2d(hidden, channels, 1)
        )

        self.spatial_conv = nn.Conv2d(
            2, 1, kernel_size=7, padding=3
        )

    def forward(self, x):
        avg = F.adaptive_avg_pool2d(x, 1)
        maximum = F.adaptive_max_pool2d(x, 1)

        channel_attention = torch.sigmoid(
            self.channel_mlp(avg) + self.channel_mlp(maximum)
        )
        x = x * channel_attention

        avg_map = x.mean(dim=1, keepdim=True)
        max_map = x.max(dim=1, keepdim=True)[0]

        spatial_attention = torch.sigmoid(
            self.spatial_conv(torch.cat([avg_map, max_map], dim=1))
        )

        return x * spatial_attention


class DecoderBlock(nn.Module):
    def __init__(self, in_channels, skip_channels, out_channels):
        super().__init__()
        self.conv = ConvBlock(
            in_channels + skip_channels, out_channels
        )

    def forward(self, x, skip):
        x = F.interpolate(
            x, size=skip.shape[-2:],
            mode="bilinear", align_corners=False
        )
        x = torch.cat([x, skip], dim=1)
        return self.conv(x)


class SiameseCBAMUNet(nn.Module):
    def __init__(self, num_classes=7):
        super().__init__()

        # Shared encoder for T1 and T2
        self.encoder = Encoder()

        # Attention on multi-scale temporal differences
        self.att1 = CBAM(32)
        self.att2 = CBAM(64)
        self.att3 = CBAM(128)
        self.att4 = CBAM(256)

        # U-Net decoder
        self.dec3 = DecoderBlock(256, 128, 128)
        self.dec2 = DecoderBlock(128, 64, 64)
        self.dec1 = DecoderBlock(64, 32, 32)

        self.output_head = nn.Conv2d(32, num_classes, 1)

    def forward(self, t1, t2):
        a1, a2, a3, a4 = self.encoder(t1)
        b1, b2, b3, b4 = self.encoder(t2)

        # Absolute feature differences at four scales
        d1 = self.att1(torch.abs(a1 - b1))
        d2 = self.att2(torch.abs(a2 - b2))
        d3 = self.att3(torch.abs(a3 - b3))
        d4 = self.att4(torch.abs(a4 - b4))

        x = self.dec3(d4, d3)
        x = self.dec2(x, d2)
        x = self.dec1(x, d1)

        return self.output_head(x)


